namespace Tanba.Storage;

/// <summary>
/// Что лежит в базе сразу после её создания.
///
/// Раньше это было в schema.sql и содержало рабочие теги одного человека:
/// пять организаций его комплекса, две кампании и имя живого коллеги. Всё
/// это раздавалось каждому, кто ставил программу, и лежало в открытом
/// репозитории.
///
/// Теперь набор маленький и ничей: одни типы работ. Остальные группы человек
/// заводит сам, потому что придумать за него, какие у него организации и
/// кампании, всё равно нельзя.
///
/// Язык берётся тот, что выбран при установке, и только в этот момент.
/// Дальше теги живут как данные: заведённые по-русски остаются русскими,
/// даже если человек переключит интерфейс на английский.
/// </summary>
public static class Seed
{
    public static void Starter(Repo repo, string lang)
    {
        var (group, types) = lang == "en"
            ? ("Type", new[] { "Banner", "Video", "Logo", "Presentation", "Photo" })
            : ("Тип", new[] { "Баннер", "Видео", "Логотип", "Презентация", "Фото" });

        using var c = repo.Open();
        var id = repo.EnsureGroup(c, group);
        foreach (var t in types) repo.EnsureTag(c, id, t);
    }
}
